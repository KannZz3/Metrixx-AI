def direction_score(direction: Any) -> float:
    value = str(direction or "").upper()
    if value == "BULLISH":
        return 1.0
    if value == "BEARISH":
        return -1.0
    if value == "MIXED":
        return 0.0
    return 0.0


def load_narrative_summary(path: Path) -> Dict[str, Dict[str, Any]]:
    payload = load_json(path)
    records = payload.get("records", []) if isinstance(payload, dict) else []
    grouped: Dict[str, List[Dict[str, Any]]] = {}
    for row in records:
        target = row.get("target_commodity") or row.get("primary_commodity")
        if target:
            grouped.setdefault(str(target), []).append(row)

    out = {}
    for symbol, rows in grouped.items():
        count = len(rows)
        if not count:
            continue
        latest = max(rows, key=lambda item: str(item.get("timestamp") or ""))
        confidence_values = [safe_float(item.get("confidence_score")) for item in rows]
        confidence_values = [value for value in confidence_values if value is not None]
        sentiment_values = [direction_score(item.get("direction")) * (safe_float(item.get("confidence_score")) or 0.0) for item in rows]
        avg_sentiment = sum(sentiment_values) / count if count else 0.0
        avg_confidence = sum(confidence_values) / len(confidence_values) if confidence_values else None
        bullish = sum(1 for item in rows if str(item.get("direction") or "").upper() == "BULLISH")
        bearish = sum(1 for item in rows if str(item.get("direction") or "").upper() == "BEARISH")
        neutral = sum(1 for item in rows if str(item.get("direction") or "").upper() == "NEUTRAL")
        unknown = sum(1 for item in rows if str(item.get("direction") or "").upper() == "UNKNOWN")
        if avg_sentiment >= 0.25:
            aggregate_direction = "bullish"
        elif avg_sentiment <= -0.25:
            aggregate_direction = "bearish"
        elif avg_sentiment > 0.05:
            aggregate_direction = "mildly_bullish"
        elif avg_sentiment < -0.05:
            aggregate_direction = "mildly_bearish"
        else:
            aggregate_direction = "neutral"
        out[symbol] = {
            "event_count": count,
            "bullish_count": bullish,
            "bearish_count": bearish,
            "neutral_count": neutral,
            "unknown_count": unknown,
            "avg_sentiment_score": round(avg_sentiment, 6),
            "avg_confidence_score": round(avg_confidence, 6) if avg_confidence is not None else None,
            "aggregate_direction": aggregate_direction,
            "latest_event_timestamp": latest.get("timestamp"),
            "top_event_headline": latest.get("headline_paraphrase") or latest.get("headline_original"),
            "tos_status": "GO_WITH_SOURCE_SPECIFIC_TOS",
            "gatekeeper_cleared": all(bool(item.get("gatekeeper_cleared")) for item in rows),
        }
    return out


