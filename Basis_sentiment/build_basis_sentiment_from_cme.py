def latest_front_by_symbol(records: List[Dict[str, Any]]) -> Dict[str, Dict[str, Any]]:
    out: Dict[str, Dict[str, Any]] = {}
    for row in records:
        if not row.get("is_front_month"):
            continue
        symbol = row.get("symbol")
        if not symbol or not row.get("trade_date"):
            continue
        current = out.get(symbol)
        if current is None or str(row["trade_date"]) > str(current.get("trade_date")):
            out[symbol] = row
    return out


def curve_context(records: List[Dict[str, Any]]) -> Dict[str, Dict[str, Any]]:
    by_symbol_date: Dict[Tuple[str, str], List[Dict[str, Any]]] = {}
    for row in records:
        symbol = row.get("symbol")
        trade_date = row.get("trade_date")
        if not symbol or not trade_date:
            continue
        by_symbol_date.setdefault((symbol, trade_date), []).append(row)

    out: Dict[str, Dict[str, Any]] = {}
    for (symbol, trade_date), rows in by_symbol_date.items():
        rows = sorted(rows, key=lambda item: int(item.get("contract_rank") or 999))
        front = next((item for item in rows if item.get("contract_rank") == 1), None)
        second = next((item for item in rows if item.get("contract_rank") == 2), None)
        if not front:
            continue
        spread = None
        signal = "not_available"
        if second:
            front_value = safe_float(front.get("settlement_common_unit_value"))
            second_value = safe_float(second.get("settlement_common_unit_value"))
            if front_value is not None and second_value is not None:
                spread = round(second_value - front_value, 8)
                if spread > 0:
                    signal = "contango"
                elif spread < 0:
                    signal = "backwardation"
                else:
                    signal = "flat"
        current = out.get(symbol)
        if current is None or trade_date > current["trade_date"]:
            out[symbol] = {
                "trade_date": trade_date,
                "front_next_spread_common": spread,
                "term_structure_signal": signal,
                "second_contract": second.get("futures_contract") if second else None,
            }
    return out


def load_eia_latest(path: Path) -> Dict[str, Dict[str, Any]]:
    payload = load_json(path)
    out = {}
    for group in payload.get("group_results", []):
        series_key = group.get("series_key")
        if not series_key:
            continue
        details = dict(EIA_SOURCE_DETAILS.get(series_key, {}))
        details.update(
            {
                "series_key": series_key,
                "timestamp": group.get("latest_timestamp"),
                "value": group.get("latest_value"),
                "tos_status": "GO",
                "gatekeeper_cleared": True,
            }
        )
        out[series_key] = details
    return out


