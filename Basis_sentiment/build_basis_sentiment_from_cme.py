def convert_for_basis(symbol: str, physical: Dict[str, Any], future: Dict[str, Any]) -> Dict[str, Any]:
    physical_value = safe_float(physical.get("physical_price_asof"))
    futures_value = safe_float(future.get("settlement_common_unit_value"))
    futures_unit = future.get("common_unit")
    physical_unit = physical.get("physical_unit")

    if symbol == "ZS" and physical.get("physical_series_key") == "SOYBEAN_MEAL":
        converted_futures = None if futures_value is None else round(futures_value * (SHORT_TON_LB / SOYBEAN_BUSHEL_WEIGHT_LB), 6)
        return {
            "basis_common_unit": "USD_PER_SHORT_TON",
            "physical_price_converted": physical_value,
            "physical_conversion_formula": "no_conversion_needed; USDA soybean meal physical is already USD_PER_SHORT_TON",
            "futures_settlement_converted": converted_futures,
            "futures_conversion_formula": "ZS futures USD_PER_BUSHEL * (2000 lb per short ton / 60 lb per soybean bushel)",
            "conversion_note": "Related proxy: soybean meal physical is compared with soybean futures converted to USD_PER_SHORT_TON; not a strict raw-soybean cash basis.",
        }

    if physical_unit == futures_unit:
        return {
            "basis_common_unit": physical_unit,
            "physical_price_converted": physical_value,
            "physical_conversion_formula": "no_conversion_needed",
            "futures_settlement_converted": futures_value,
            "futures_conversion_formula": future.get("unit_conversion"),
            "conversion_note": f"Physical and futures legs are both in {physical_unit}.",
        }

    return {
        "basis_common_unit": None,
        "physical_price_converted": physical_value,
        "physical_conversion_formula": "unsupported_conversion",
        "futures_settlement_converted": futures_value,
        "futures_conversion_formula": future.get("unit_conversion"),
        "conversion_note": f"Unsupported unit pairing: physical={physical_unit}, futures={futures_unit}.",
    }


def basis_quality(trade_date: Any, physical_date: Any, max_lag_days: int) -> Tuple[Optional[int], str, str]:
    lag = day_diff(trade_date, physical_date)
    if lag is None:
        return None, "PHYSICAL_DATE_UNKNOWN", "INCOMPLETE_MISSING_PHYSICAL_DATE"
    if lag == 0:
        return lag, "EXACT_DATE_PHYSICAL", "COMPLETE_EXACT_DATE_PHYSICAL"
    if 0 < lag <= max_lag_days:
        return lag, f"ASOF_PHYSICAL_ACCEPTED_LAG_{lag}D", "COMPLETE_WITH_LATEST_AVAILABLE_ASOF_PHYSICAL"
    if lag > max_lag_days:
        return lag, f"STALE_PHYSICAL_LAG_{lag}D_REVIEW", "COMPLETE_WITH_STALE_PHYSICAL_REVIEW"
    return lag, "PHYSICAL_DATE_AFTER_FUTURES_REVIEW", "COMPLETE_WITH_DATE_ALIGNMENT_REVIEW"


def build_row(
    symbol: str,
    future: Dict[str, Any],
    mapping: Optional[Dict[str, Any]],
    physical_source: Optional[Dict[str, Any]],
    cot: Optional[Dict[str, Any]],
    narrative: Optional[Dict[str, Any]],
    curve: Optional[Dict[str, Any]],
    max_lag_days: int,
) -> Dict[str, Any]:
    available = ["cme_futures_settlement"]
    missing = []
    row = {
        "trade_date": future.get("trade_date"),
        "symbol": symbol,
        "basis_label": mapping.get("basis_label") if mapping else f"{symbol}_FUTURES_ONLY",
        "instrument": future.get("instrument"),
        "commodity_label": future.get("commodity_label"),
        "exchange": future.get("exchange"),
        "futures_contract": future.get("futures_contract"),
        "is_front_month": future.get("is_front_month"),
        "futures_settlement_raw": future.get("settlement_price"),
        "futures_price_unit": future.get("price_unit"),
        "futures_settlement_common": future.get("settlement_common_unit_value"),
        "volume": future.get("volume"),
        "transactions": future.get("transactions"),
        "front_next_spread_common": curve.get("front_next_spread_common") if curve else None,
        "term_structure_signal": curve.get("term_structure_signal") if curve else None,
        "merged_at_utc": utc_now(),
    }

    if curve and curve.get("front_next_spread_common") is not None:
        available.append("term_structure")

    if physical_source and mapping:
        physical = normalize_physical_fields(physical_source, mapping)
        row.update(physical)
        row["physical_component_role"] = "PHYSICAL_PRICE_LATEST_AVAILABLE_ASOF"
        conversion = convert_for_basis(symbol, physical, future)
        row.update(conversion)
        lag, quality_flag, input_status = basis_quality(row.get("trade_date"), row.get("physical_price_asof_date"), max_lag_days)
        row["physical_lag_days"] = lag
        physical_converted = safe_float(row.get("physical_price_converted"))
        futures_converted = safe_float(row.get("futures_settlement_converted"))
        basis_ready = physical_converted is not None and futures_converted is not None and row.get("basis_common_unit") is not None
        row["basis_ready"] = basis_ready
        if basis_ready:
            row["basis_value_asof"] = round(physical_converted - futures_converted, 6)
            row["basis_value_asof_status"] = "CALCULATED_WITH_LATEST_AVAILABLE_ASOF_PHYSICAL"
            row["basis_formula_asof"] = "physical_price_asof - front_month_futures_settlement"
            available.append("physical_latest_available_asof")
        else:
            row["basis_value_asof"] = None
            row["basis_value_asof_status"] = "NOT_CALCULATED_UNIT_OR_VALUE_MISSING"
            row["basis_formula_asof"] = None
            missing.append("basis_conversion")
        row["basis_quality_flag"] = quality_flag
        row["basis_calculation_input_status"] = input_status
    else:
        row.update(
            {
                "physical_component_role": "NO_PHYSICAL_MAPPING_AVAILABLE",
                "basis_ready": False,
                "basis_value_asof": None,
                "basis_value_asof_status": "NOT_CALCULATED_NO_PHYSICAL_MAPPING",
                "basis_quality_flag": "NO_PHYSICAL_MAPPING_AVAILABLE",
                "basis_calculation_input_status": "INCOMPLETE_NO_PHYSICAL_MAPPING",
            }
        )
        missing.append("physical_price")

    if cot:
        available.append("cot_overlay")
        row.update(
            {
                "cot_score": cot.get("cot_score"),
                "cot_signal": cot.get("cot_signal"),
                "cot_confidence": cot.get("confidence"),
                "cot_report_date": cot.get("report_date"),
                "cot_lag_days": day_diff(row.get("trade_date"), cot.get("report_date")),
                "cot_score_status": cot.get("score_status"),
                "cot_summary": cot.get("summary"),
            }
        )
    else:
        missing.append("cot_overlay")

    if narrative:
        available.append("narrative_sentiment")
        row.update(
            {
                "narrative_event_count": narrative.get("event_count"),
                "narrative_bullish_count": narrative.get("bullish_count"),
                "narrative_bearish_count": narrative.get("bearish_count"),
                "narrative_neutral_count": narrative.get("neutral_count"),
                "narrative_unknown_count": narrative.get("unknown_count"),
                "narrative_avg_sentiment_score": narrative.get("avg_sentiment_score"),
                "narrative_avg_confidence_score": narrative.get("avg_confidence_score"),
                "narrative_aggregate_direction": narrative.get("aggregate_direction"),
                "narrative_latest_event_timestamp": narrative.get("latest_event_timestamp"),
                "narrative_lag_days": day_diff(row.get("trade_date"), narrative.get("latest_event_timestamp")),
                "narrative_top_event_headline": narrative.get("top_event_headline"),
                "narrative_tos_status": narrative.get("tos_status"),
                "narrative_gatekeeper_cleared": narrative.get("gatekeeper_cleared"),
            }
        )
    else:
        missing.append("narrative_sentiment")

    row["available_components"] = ";".join(available)
    row["missing_components"] = ";".join(missing)
    return row


def validate_output(rows: List[Dict[str, Any]]) -> Dict[str, Any]:
    basis_rows = [row for row in rows if row.get("basis_ready")]
    stale_rows = [row for row in rows if str(row.get("basis_quality_flag") or "").startswith("STALE_")]
    futures_only_rows = [row for row in rows if row.get("physical_component_role") == "NO_PHYSICAL_MAPPING_AVAILABLE"]
    errors = []
    if not rows:
        errors.append("No basis sentiment rows were generated.")
    if not basis_rows:
        errors.append("No basis-ready rows were generated.")
    return {
        "validated_at": utc_now(),
        "stage": "basis_sentiment_from_massive_cme",
        "all_required_ok": not errors,
        "record_count": len(rows),
        "basis_ready_count": len(basis_rows),
        "stale_physical_review_count": len(stale_rows),
        "futures_only_count": len(futures_only_rows),
        "symbols": sorted({row.get("symbol") for row in rows if row.get("symbol")}),
        "basis_labels": [row.get("basis_label") for row in rows],
        "errors": errors,
        "warnings": [
            "Rows with STALE_PHYSICAL_* flags are calculated but should be reviewed before publication.",
            "ZS uses soybean meal as a related physical proxy, matching the existing repository sample logic.",
            "GC and SI are emitted as futures-only rows because no physical basis leg is present in the current public subset.",
        ],
    }


def parse_args() -> argparse.Namespace:
    repo_root = Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--cme-json", type=Path, default=repo_root / "Data_light_version/CME/massive_cme_futures_normalized.json")
    parser.add_argument("--eia-validation", type=Path, default=repo_root / "Data_light_version/EIA/eia_normalization_validation_report.json")
    parser.add_argument("--usda-json", type=Path, default=repo_root / "Data_light_version/USDA/usda_grain_physical_prices_normalized.json")
    parser.add_argument("--cot-json", type=Path, default=repo_root / "COT_scoring_positioning/cftc_cot_scores.json")
    parser.add_argument("--narrative-json", type=Path, default=repo_root / "Data_light_version/Reuters/narrative_events_normalized.json")
    parser.add_argument("--out-dir", type=Path, default=repo_root / "Basis_sentiment")
    parser.add_argument("--max-accepted-physical-lag-days", type=int, default=DEFAULT_MAX_ACCEPTED_PHYSICAL_LAG_DAYS)
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    cme_records = load_cme_records(args.cme_json)
    latest_futures = latest_front_by_symbol(cme_records)
    curve = curve_context(cme_records)
    eia = load_eia_latest(args.eia_validation)
    usda = load_usda_latest(args.usda_json)
    cot = load_latest_cot(args.cot_json)
    narrative = load_narrative_summary(args.narrative_json)

    rows: List[Dict[str, Any]] = []
    for symbol in sorted(latest_futures):
        future = latest_futures[symbol]
        mappings = BASIS_MAPPINGS.get(symbol, [])
        if not mappings:
            rows.append(
                build_row(
                    symbol,
                    future,
                    None,
                    None,
                    cot.get(symbol),
                    narrative.get(symbol),
                    curve.get(symbol),
                    args.max_accepted_physical_lag_days,
                )
            )
            continue
        for mapping in mappings:
            rows.append(
                build_row(
                    symbol,
                    future,
                    mapping,
                    physical_record(mapping, eia, usda),
                    cot.get(symbol),
                    narrative.get(symbol),
                    curve.get(symbol),
                    args.max_accepted_physical_lag_days,
                )
            )

    rows.sort(key=lambda row: (row.get("symbol") or "", row.get("basis_label") or ""))
    payload = {
        "generated_at": utc_now(),
        "source": "BASIS_SENTIMENT_FROM_MASSIVE_CME",
        "stage": "futures_physical_cot_narrative_merge",
        "records": rows,
    }
    validation = validate_output(rows)
    args.out_dir.mkdir(parents=True, exist_ok=True)
    save_json(args.out_dir / "basis_sentiment_from_massive_cme.json", payload)
    write_csv(args.out_dir / "basis_sentiment_from_massive_cme.csv", rows)
    save_json(args.out_dir / "basis_sentiment_from_massive_cme_validation_report.json", validation)
    print(f"records={len(rows)}")
    print(f"basis_ready_count={validation['basis_ready_count']}")
    print(f"validation_ok={validation['all_required_ok']}")
    return 0 if validation["all_required_ok"] else 1


if __name__ == "__main__":
    raise SystemExit(main())
