def utc_now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def load_json(path: Path) -> Any:
    with path.open("r", encoding="utf-8") as handle:
        return json.load(handle)


def save_json(path: Path, payload: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as handle:
        json.dump(payload, handle, ensure_ascii=False, indent=2)
        handle.write("\n")


def write_csv(path: Path, rows: List[Dict[str, Any]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    keys = list(PREFERRED_CSV_FIELDS)
    for row in rows:
        for key in row:
            if key not in keys:
                keys.append(key)
    with path.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=keys)
        writer.writeheader()
        for row in rows:
            out = {}
            for key in keys:
                value = row.get(key)
                out[key] = json.dumps(value, ensure_ascii=False) if isinstance(value, (dict, list)) else value
            writer.writerow(out)


def parse_dt(value: Any) -> Optional[datetime]:
    if value in (None, ""):
        return None
    text = str(value).strip()
    for fmt in ("%Y-%m-%dT%H:%M:%S%z", "%Y-%m-%dT%H:%M:%S+00:00", "%Y-%m-%d", "%m/%d/%Y"):
        try:
            if fmt == "%Y-%m-%dT%H:%M:%S%z":
                return datetime.fromisoformat(text.replace("Z", "+00:00"))
            return datetime.strptime(text[:10] if fmt == "%Y-%m-%d" else text, fmt)
        except Exception:
            pass
    return None


def day_diff(later: Any, earlier: Any) -> Optional[int]:
    later_dt = parse_dt(later)
    earlier_dt = parse_dt(earlier)
    if not later_dt or not earlier_dt:
        return None
    return (later_dt.date() - earlier_dt.date()).days


def safe_float(value: Any) -> Optional[float]:
    if value in (None, ""):
        return None
    try:
        return float(value)
    except Exception:
        return None


